def _fmt(v):
    return f"{v:,.2f}"


def expense_pdf(qs, user, meta, scope_label):
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=landscape(A4), leftMargin=12 * mm, rightMargin=12 * mm,
                            topMargin=12 * mm, bottomMargin=14 * mm, title="Expense register")
    styles = getSampleStyleSheet()
    small = styles["BodyText"].clone("small", fontSize=7.5, leading=9)
    story = [Paragraph("Expense register", styles["Title"])]
    for k, v in _meta_lines(user, meta, scope_label):
        if k != "Report":
            story.append(Paragraph(f"<b>{k}:</b> {v}", small))
    story.append(Spacer(1, 4 * mm))

    head = ["Ref", "Date", "Expense", "Entity", "Category", "Vendor", "Status", "Cur", "Taxable", "GST", "Gross"]
    data = [head]
    for e in _prefetch(qs):
        data.append([e.ref, e.expense_date.strftime("%d-%m-%Y"), Paragraph(e.title, small), e.paying_entity.code,
                     Paragraph(e.category.name, small), Paragraph(e.vendor_name_snapshot or "", small),
                     e.get_status_display(), e.currency, _fmt(e.taxable_value), _fmt(e.total_gst),
                     _fmt(e.gross_amount)])
    totals = totals_by_currency(qs)
    for t in totals:
        data.append(["", "", f"Total ({t['count']} records)", "", "", "", "", t["currency"], _fmt(t["taxable"]),
                     _fmt(t["gst"]), _fmt(t["gross"])])
    widths = [22, 20, 60, 18, 32, 40, 30, 11, 25, 22, 25]
    table = Table(data, colWidths=[w * mm for w in widths], repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1F3A5F")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 0), (-1, -1), 7.5),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("ALIGN", (8, 0), (-1, -1), "RIGHT"),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1 - len(totals)), [colors.white, colors.HexColor("#F3F5F8")]),
        ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#D5DAE1")),
    ]
    if totals:
        style += [("FONTNAME", (0, -len(totals)), (-1, -1), "Helvetica-Bold"),
                  ("LINEABOVE", (0, -len(totals)), (-1, -len(totals)), 1, colors.black)]
    table.setStyle(TableStyle(style))
    story.append(table)

    def page(canvas, doc_):
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.drawRightString(landscape(A4)[0] - 12 * mm, 8 * mm, f"Page {doc_.page}")
        canvas.drawString(12 * mm, 8 * mm, "Company Expense Management – Expense register")
        canvas.restoreState()

    doc.build(story, onFirstPage=page, onLaterPages=page)
    return buf.getvalue()


def gst_summary(qs):
    """GST summary by entity, period, tax type and ITC status (FR-GST-009)."""
    groups = defaultdict(lambda: defaultdict(Decimal))
    for r in qs.values("paying_entity__code", "expense_date__year", "expense_date__month", "gst_type",
                       "itc_status").annotate(taxable=Sum("taxable_value"), cgst=Sum("cgst_amount"),
                                              sgst=Sum("sgst_utgst_amount"), igst=Sum("igst_amount"),
                                              cess=Sum("cess_amount"), itc=Sum("verified_itc_amount"),
                                              n=Count("id")):
        key = (r["paying_entity__code"], f"{r['expense_date__year']}-{r['expense_date__month']:02d}",
               r["gst_type"] or "—", r["itc_status"])
        for k in ("taxable", "cgst", "sgst", "igst", "cess", "itc", "n"):
            groups[key][k] += r[k] or 0
    return [{"entity": k[0], "period": k[1], "gst_type": k[2], "itc_status": k[3],
             **{m: str(v) for m, v in vals.items()}} for k, vals in sorted(groups.items())]
