HEADER_FILL = PatternFill("solid", fgColor="1F3A5F")
HEADER_FONT = Font(bold=True, color="FFFFFF")


def _row_values(e):
    values = {
        "ExpenseRef": e.ref, "ExternalRecordID": e.external_record_id or "", "ExpenseName": e.title,
        "ExpenseDate": e.expense_date, "PayingEntityCode": e.paying_entity.code,
        "BeneficiaryEntityCode": e.beneficiary_entity.code if e.beneficiary_entity else "",
        "EmployeeCode": getattr(getattr(e.submitter, "profile", None), "employee_code", ""),
        "CategoryCode": e.category.code, "DepartmentCode": e.department.code if e.department else "",
        "ProjectCode": e.project.code if e.project else "", "Description": e.description,
        "VendorName": e.vendor_name_snapshot, "SupplierGSTIN": e.supplier_gstin,
        "SupplierStateCode": e.supplier_state_code, "PlaceOfSupplyStateCode": e.place_of_supply_state_code,
        "InvoiceNumber": e.invoice_number, "InvoiceDate": e.invoice_date or "", "Currency": e.currency,
        "TaxableValue": e.taxable_value, "GSTType": e.gst_type, "GSTRate": e.gst_rate if e.gst_rate is not None else "",
        "CGSTAmount": e.cgst_amount, "SGSTAmount": e.sgst_utgst_amount, "IGSTAmount": e.igst_amount,
        "CessAmount": e.cess_amount, "OtherCharges": e.other_charges, "GrossAmount": e.gross_amount,
        "PaymentMethod": e.payment_method.code if e.payment_method else "", "Notes": e.notes, "SourceNotes": "",
        "Status": e.get_status_display(), "TotalGST": e.total_gst, "ITCStatus": e.get_itc_status_display(),
        "VerifiedITC": e.verified_itc_amount, "Submitter": e.submitter.get_full_name() or e.submitter.username,
        "Source": e.get_source_type_display(), "DuplicateSuspect": "Yes" if e.duplicate_suspect else "",
    }
    return values


EXPORT_HEADERS = HEADERS + EXPORT_ONLY


def _prefetch(qs):
    return qs.select_related("paying_entity", "beneficiary_entity", "category", "department", "project",
                             "payment_method", "submitter", "submitter__profile").order_by("expense_date", "ref")


def totals_by_currency(qs):
    rows = qs.values("currency").annotate(n=Count("id"), gross=Sum("gross_amount"), taxable=Sum("taxable_value"),
                                          cgst=Sum("cgst_amount"), sgst=Sum("sgst_utgst_amount"),
                                          igst=Sum("igst_amount"), cess=Sum("cess_amount"),
                                          itc=Sum("verified_itc_amount")).order_by("currency")
    out = []
    for r in rows:
        gst = sum((r[k] or Decimal("0")) for k in ("cgst", "sgst", "igst", "cess"))
        out.append({"currency": r["currency"], "count": r["n"], "gross": r["gross"] or Decimal("0"),
                    "taxable": r["taxable"] or Decimal("0"), "gst": gst, "verified_itc": r["itc"] or Decimal("0")})
    return out


def _meta_lines(user, meta, scope_label):
    f = meta["filters"]
    return [
        ("Report", "Expense register"),
        ("Generated", timezone.localtime().strftime("%d %b %Y %H:%M %Z")),
        ("Generated by", user.get_full_name() or user.username),
        ("Entity scope", scope_label),
        ("Status inclusion", meta["status_rule"]),
        ("Filters", ", ".join(f"{k}={v}" for k, v in f.items()) or "None"),
        ("Amounts", "Gross = taxable value + recorded GST + other charges. Recorded GST is not eligible ITC."),
    ]


def expense_csv(qs):
    buf = io.StringIO()
    buf.write("﻿")  # BOM so Excel opens UTF-8 correctly (₹, names)
    w = csv.writer(buf)
    w.writerow(EXPORT_HEADERS)
    for e in _prefetch(qs):
        v = _row_values(e)
        w.writerow([v[h] for h in EXPORT_HEADERS])
    return buf.getvalue().encode("utf-8")


def _style_header(ws, row, ncols):
    for c in range(1, ncols + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(vertical="center")


def expense_xlsx(qs, user, meta, scope_label):
    wb = Workbook()
    ws = wb.active
    ws.title = "Expenses"
    ws.append(EXPORT_HEADERS)
    _style_header(ws, 1, len(EXPORT_HEADERS))
    money_cols = {i + 1 for i, h in enumerate(EXPORT_HEADERS)
                  if h in ("TaxableValue", "CGSTAmount", "SGSTAmount", "IGSTAmount", "CessAmount", "OtherCharges",
                           "GrossAmount", "TotalGST", "VerifiedITC")}
    date_cols = {i + 1 for i, h in enumerate(EXPORT_HEADERS) if h in ("ExpenseDate", "InvoiceDate")}
    n = 1
    for e in _prefetch(qs):
        v = _row_values(e)
        ws.append([v[h] for h in EXPORT_HEADERS])
        n += 1
        for c in money_cols:
            ws.cell(row=n, column=c).number_format = "#,##0.00"
        for c in date_cols:
            ws.cell(row=n, column=c).number_format = "yyyy-mm-dd"
    ws.freeze_panes = "A2"
    if n > 1:
        ws.auto_filter.ref = f"A1:{get_column_letter(len(EXPORT_HEADERS))}{n}"
    for i, h in enumerate(EXPORT_HEADERS, start=1):
        ws.column_dimensions[get_column_letter(i)].width = max(12, min(40, len(h) + 4))
    ws.column_dimensions["C"].width = 32

    info = wb.create_sheet("Report info")
    for k, val in _meta_lines(user, meta, scope_label):
        info.append([k, val])
        info.cell(row=info.max_row, column=1).font = Font(bold=True)
    info.append([])
    info.append(["Totals by currency"])
    info.cell(row=info.max_row, column=1).font = Font(bold=True)
    info.append(["Currency", "Records", "Taxable value", "Recorded GST", "Gross", "Verified ITC"])
    _style_header(info, info.max_row, 6)
    for t in totals_by_currency(qs):
        info.append([t["currency"], t["count"], t["taxable"], t["gst"], t["gross"], t["verified_itc"]])
        for c in range(3, 7):
            info.cell(row=info.max_row, column=c).number_format = "#,##0.00"
    info.column_dimensions["A"].width = 20
    info.column_dimensions["B"].width = 60

    summary = wb.create_sheet("By category")
    summary.append(["Category", "Records", "Gross", "Recorded GST"])
    _style_header(summary, 1, 4)
    for r in qs.values("category__name").annotate(n=Count("id"), gross=Sum("gross_amount"),
                                                  c=Sum("cgst_amount"), s=Sum("sgst_utgst_amount"),
                                                  i=Sum("igst_amount"), x=Sum("cess_amount")).order_by("-gross"):
        summary.append([r["category__name"], r["n"], r["gross"],
                        sum((r[k] or 0) for k in ("c", "s", "i", "x"))])
        summary.cell(row=summary.max_row, column=3).number_format = "#,##0.00"
        summary.cell(row=summary.max_row, column=4).number_format = "#,##0.00"
    summary.column_dimensions["A"].width = 30
    out = io.BytesIO()
    wb.save(out)
    return out.getvalue()


